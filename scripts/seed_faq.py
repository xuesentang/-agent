async def seed(database_url: str, clear: bool) -> int:
    engine = create_async_engine(database_url)
    try:
        async with engine.begin() as conn:
            if clear:
                await conn.execute(text("DELETE FROM faq"))
            await conn.execute(
                text("INSERT INTO faq (question, answer, category) VALUES (:q, :a, :c)"),
                [{"q": q, "a": a, "c": c} for q, a, c in FAQ_ROWS],
            )
        return len(FAQ_ROWS)
    finally:
        await engine.dispose()


def main() -> None:
    parser = argparse.ArgumentParser(description="Seed faq table (AI 合成数据)")
    parser.add_argument("--database-url", default=get_settings().database_url)
    parser.add_argument("--no-clear", action="store_true", help="追加插入,不清空旧数据")
    args = parser.parse_args()
    count = asyncio.run(seed(args.database_url, clear=not args.no_clear))
    print(f"seeded {count} faq rows into {args.database_url}")


if __name__ == "__main__":
    main()
