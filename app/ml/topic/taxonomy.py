"""17 类权威类目表(第十章需求 1)。

## 为什么写在代码里

这张表要同时喂三个地方:训练标签顺序、预标 Prompt、前端图表文案。抄三份必然有一份
先过期,而且过期了不会报错——只是分类结果慢慢错位。所以只留这一份,别的都从这里取。

## 边界说明不是装饰

近邻类目靠一句话划开,这句话直接进预标 Prompt:「修归保修维修、退归退换货;
运费管钱、物流管货;价保补差价、优惠活动是券和满减」。没有这几句,模型和人工标注
都会在「退货的运费谁出」这种句子上分不清该打「退换货」还是「运费」——答案是两个都打。
"""

from __future__ import annotations

# 顺序即模型输出位次,改顺序等于让旧模型全表标错
LABELS: tuple[str, ...] = (
    "退换货",
    "物流",
    "尺码",
    "发票",
    "质量问题",
    "运费",
    "优惠活动",
    "价保",
    "支付",
    "订单修改",
    "库存补货",
    "商品信息",
    "保修维修",
    "账号",
    "会员积分",
    "评价",
    "其他",
)

# 每类一句边界说明:说「这一类管什么」,顺带把近邻挡在外面
BOUNDARIES: dict[str, str] = {
    "退换货": "退货、换货、退款的诉求本身;退回到账时间也算这一类",
    "物流": "包裹在路上:到哪了、多久到、为什么停滞、显示签收但没收到",
    "尺码": "大小与码数:偏大偏小、码表、合不合脚、宽楦窄楦",
    "发票": "开不开票、发票类型、抬头税号、发票丢失重开",
    "质量问题": "商品本身的破损、开胶、掉色、异味、做工问题(不含保修期内的维修)",
    "运费": "运费谁出、多少、包邮门槛、退货运费承担方(钱的事归这里)",
    "优惠活动": "优惠券、满减、折扣、活动规则与叠加限制",
    "价保": "买了之后降价,申请补差价",
    "支付": "付款方式、扣款失败、重复扣款、支付渠道异常",
    "订单修改": "改收货地址、改商品规格、取消未发货订单",
    "库存补货": "缺货、什么时候补货、能不能到货提醒",
    "商品信息": "材质、型号、参数、适配与兼容、和别款的区别",
    "保修维修": "保修期与范围、报修流程、换配件、上门维修",
    "账号": "登录不上、换绑手机号、改密码、注销账号",
    "会员积分": "会员等级与权益、积分怎么攒和怎么用",
    "评价": "晒单、评价入口、差评与追评、评价能否修改",
    "其他": "以上都不是,或信息不足无法归类",
}

# 近邻类目的划界口径,合成一句话直接进 Prompt
NEIGHBOR_RULES: str = (
    "修归保修维修、退归退换货;运费管钱、物流管货;"
    "价保是补差价、优惠活动是券和满减。"
    "一句话里同时提到多个诉求就打多个标签,不许多打也不许漏打。"
)


def taxonomy_prompt_block() -> str:
    """给大模型看的类目块:一行一类,带边界说明。"""
    lines = [f"- {label}:{BOUNDARIES[label]}" for label in LABELS]
    return "\n".join(lines)


def validate_labels(labels) -> list[str]:
    """把模型吐的标签收敛成图例内的合法标签。

    - 去重保序(同一句里重复出现的标签只留一次)
    - 丢掉不在表里的(模型偶尔会自造类目,留着会污染统计)
    - 全被丢光时给「其他」——业务上不允许空标签,空了对分布页就是个黑洞
    """
    seen: list[str] = []
    for label in labels or []:
        text = str(label).strip()
        if text in LABELS and text not in seen:
            seen.append(text)
    return seen or ["其他"]
