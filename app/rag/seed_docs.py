SEED_DOCS: dict[str, str] = {
    "return_policy.md": RETURN_POLICY_MD,
    "product_faq.md": PRODUCT_FAQ_MD,
    "after_sales_manual.md": AFTER_SALES_MANUAL_MD,
}


def write_seed_docs(target_dir: Path, force: bool = False) -> tuple[list[Path], list[Path]]:
    """把种子文档写入 target_dir,返回 (written, skipped)。

    已存在的文件默认跳过(保留使用者对文档的就地修改),--force 才覆盖。
    """
    target_dir = Path(target_dir)
    target_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    skipped: list[Path] = []
    for name, content in SEED_DOCS.items():
        path = target_dir / name
        if path.exists() and not force:
            skipped.append(path)
            continue
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written, skipped
